#!/usr/bin/env python3
"""Write syn/mosaic.pcf from gen/design.py -- the same table the board uses.

    python3 syn/gen_pcf.py [out.pcf]

⚠ THE PIN ASSIGNMENT IS ONE FACT.  design.FPGA_PINS is what gen_pcb.py lays the
copper from; if the .pcf were typed out beside it, the two would be free to
disagree and the only symptom would be a board that does not work.  That is
ERRATA E-16's shape, and it has already cost this project a day.

⚠ EVERY C64-FACING PIN GETS `-pullup no`, AND THAT IS A REQUIREMENT, NOT A
DEFAULT.  /IRQ, /NMI and /RES are 3K3 open-collector wire-OR nets in the machine
(RP3/RP4/R36).  An internal pull-up here sits in PARALLEL with those across the
level shifter and fights every other device on the line.  The plan called this
out on day one and it is enforced here rather than remembered.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "gen"))
from design import FPGA_PINS, FPGA_CFG, SLUG

# The bus signals are vectors in rtl/top.v; everything else is a scalar of the
# same name.  A pin whose signal is not matched here is a hard error, not a
# warning, because an unconstrained port is placed wherever nextpnr likes.
def port_of(sig):
    if sig.startswith("A") and sig[1:].isdigit():   return f"A[{sig[1:]}]"
    if sig.startswith("D") and sig[1:].isdigit():   return f"D[{sig[1:]}]"
    if sig.startswith("P") and sig[1:].isdigit():   return f"P[{sig[1:]}]"
    return sig

lines = ["# GENERATED by syn/gen_pcf.py from gen/design.py -- DO NOT EDIT.",
         "# Every C64-facing pin is -pullup no; see the module docstring.", ""]
for pin, sig in sorted(FPGA_PINS.items()):
    lines.append(f"set_io -nowarn -pullup no {port_of(sig)} {pin}")

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), f"{SLUG}.pcf")
open(out, "w").write("\n".join(lines) + "\n")
print(f"  {len(FPGA_PINS)} pins -> {out}")
print(f"  config pins NOT constrained here (the tool owns them): {FPGA_CFG}")
